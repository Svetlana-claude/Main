# Выпрямление и обрезка снимков плакатов об отказах: углы листа (или поля снимка)
# размечены вручную по сетке; лист поворачивается так, чтобы купол был сверху.
import cv2, numpy as np, sys
SRC='/home/mokeeva/main/exchange/otkazy-yadisk/photo_2026-10-12_12-'
OUT=sys.argv[1]  # запуск: python obrabotka.py <папка>, затем uluchshenie.py <папка> <итог>; в проекте кадры переименованы plakat-01…16 в том же порядке
W,H=1200,848  # единый формат, пропорция листа A-формата
# снимок: (ЛВ, ПВ, ПН, ЛН) в координатах фото, режим: cover — обрезать до формата, contain — дополнить белым
U={
 '34-25':((82,83),(806,93),(812,1140),(115,1180),'cover'),
 '38-53':((224,303),(803,303),(799,1134),(228,1136),'cover'),
 '38-56':((118,152),(803,168),(797,1152),(152,1172),'cover'),
 '38-58':((127,130),(853,150),(850,1168),(160,1192),'cover'),
 '39-01':((100,152),(860,184),(834,1117),(93,1119),'cover'),
 '39-03':((104,234),(860,266),(834,1042),(98,1044),'cover'),
 '39-05':((119,151),(851,179),(819,1089),(119,1099),'cover'),
 '39-08':((119,101),(839,149),(821,1153),(126,1176),'cover'),
 '39-10':((133,121),(854,134),(849,1168),(164,1207),'cover'),
 '39-12':((151,81),(884,96),(879,1149),(181,1188),'cover'),
 '39-14':((113,101),(853,118),(867,1181),(129,1194),'cover'),
 '39-16':((103,116),(824,141),(819,1168),(128,1203),'cover'),
 '39-20':((148,96),(844,126),(841,1134),(146,1159),'cover'),
 '39-22':((163,101),(847,152),(810,1144),(131,1213),'cover'),
 '39-25':((151,148),(810,184),(814,1169),(133,1179),'cover'),
 '39-26':((96,134),(837,151),(834,1224),(121,1251),'cover'),
}
NIZ={'38-53':0.0,'39-01':0.0,'39-05':0.0}  # доля кадра снизу под логотипы; у фото без логотипов — 0
for n,(tl,tr,br,bl,rezhim) in U.items():
    im=cv2.imread(SRC+n+'.jpg')
    q=np.float32([tl,tr,br,bl])
    # поджимаем на 1,75 %: срезаем кромку листа и полоски нижних листов
    c=q.mean(0); q=c+(q-c)*(0.965 if rezhim=='cover' else 0.985)
    dl=lambda a,b: np.linalg.norm(q[a]-q[b])
    dlina=(dl(0,3)+dl(1,2))/2; shir=(dl(0,1)+dl(3,2))/2   # по фото: вертикаль, горизонталь
    k=1.6; w,h=int(dlina*k),int(shir*k)                    # после поворота: ширина = вертикаль фото
    # поворот на 90° против часовой: ПВ→ЛВ, ПН→ПВ, ЛН→ПН, ЛВ→ЛН
    dst=np.float32([[0,h],[0,0],[w,0],[w,h]])
    M=cv2.getPerspectiveTransform(q,dst)
    r=cv2.warpPerspective(im,M,(w,h),flags=cv2.INTER_LANCZOS4)
    # снизу на плакатах — полоса логотипов и подпись сайта: срезаем
    r=r[:int(r.shape[0]*(1-NIZ.get(n,0.085)))]; h,w=r.shape[:2]
    if rezhim=='cover':
        # ещё 1,5 % с краёв — уголки нижних листов
        s=max(W/w,H/h)*1.03; r=cv2.resize(r,(round(w*s),round(h*s)),interpolation=cv2.INTER_AREA if s<1 else cv2.INTER_CUBIC)
        y=(r.shape[0]-H)//2; x=(r.shape[1]-W)//2; r=r[y:y+H,x:x+W]
    else:
        r=r[8:-10,4:-4]; h,w=r.shape[:2]  # полоски нижнего листа сверху и снизу
        s=min(W/w,H/h); r=cv2.resize(r,(round(w*s),round(h*s)),interpolation=cv2.INTER_CUBIC)
        bum=np.median(r[-40:-15, 10:80].reshape(-1,3),0)  # цвет бумаги — по полю у надписи
        fon=np.full((H,W,3),bum,np.uint8)
        y=(H-r.shape[0])//2; x=(W-r.shape[1])//2; fon[y:y+r.shape[0],x:x+r.shape[1]]=r; r=fon
    cv2.imwrite(f'{OUT}/{n}.jpg',r,[cv2.IMWRITE_JPEG_QUALITY,90])
    print(n,w,h,rezhim)
