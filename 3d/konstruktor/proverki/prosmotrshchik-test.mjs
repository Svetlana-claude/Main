// Проверка выложенного просмотрщика: открывается по ссылке и внутри чужой страницы.
import { chromium } from 'playwright-core';
import { readdirSync } from 'node:fs';
const kesh = process.env.HOME + '/.cache/ms-playwright/chromium-1234/';
const chrome = kesh + readdirSync(kesh).find((d) => d.startsWith('chrome-')) + '/chrome';
const ADRES = process.env.ADRES || 'http://127.0.0.1:8788/';
const b = await chromium.launch({ executablePath: chrome, args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const s = await b.newPage({ viewport: { width: 1280, height: 800 } });
const oshibki = [];
s.on('pageerror', (e) => oshibki.push(String(e)));
s.on('console', (m) => { if (m.type() === 'error') oshibki.push(m.text()); });
const itog = [];
const ok = (u, t) => itog.push((u ? 'OK   ' : 'FAIL ') + t);
await s.goto(ADRES);
await s.waitForSelector('.dv-tabl tr[data-id]', { timeout: 20000 });
await s.waitForTimeout(1200);
ok(await s.locator('.dv-tabl tr[data-id]').count() === 10, 'по ссылке: таблица из 10 деталей');
ok(await s.locator('.dv-num').count() === 10, 'по ссылке: номера на деталях');
ok(await s.locator('.dv button:text-is("Раскачка")').count() === 1, 'по ссылке: кнопки анимаций');
ok(await s.locator('input[type=file], .vkladki, #b-sohranit').count() === 0, 'по ссылке: редактора нет');
await s.click('.dv-tabl tr[data-id="kupol"]');
ok(await s.locator('.dv-num.akt').textContent() === '2', 'по ссылке: клик по строке подсвечивает деталь');
await s.screenshot({ path: '/tmp/v1.png' });
await s.goto('http://127.0.0.1:8765/proverki/vstavka.html');
const f = s.frameLocator('#vst');
await f.locator('.dv-tabl tr[data-id]').first().waitFor({ timeout: 20000 });
await s.waitForTimeout(1200);
ok(await f.locator('.dv-tabl tr[data-id]').count() === 10, 'во вставке на чужой странице: модель открылась');
await s.screenshot({ path: '/tmp/v2.png' });
ok(oshibki.length === 0, 'ошибок нет' + (oshibki.length ? ': ' + oshibki.join(' | ') : ''));
console.log(itog.join('\n'));
await b.close();
