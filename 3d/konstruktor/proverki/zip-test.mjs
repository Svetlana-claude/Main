// Архив ZIP в окне чата: фото распаковываются и сохраняются, лишнее пропускается.
import { chromium } from 'playwright-core';
import { readdirSync } from 'node:fs';
const kesh = process.env.HOME + '/.cache/ms-playwright/chromium-1234/';
const chrome = kesh + readdirSync(kesh).find((d) => d.startsWith('chrome-')) + '/chrome';
const { ADRES, KUKA } = process.env;
const b = await chromium.launch({ executablePath: chrome, args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const k = await b.newContext({ viewport: { width: 1440, height: 900 } });
await k.addCookies([{ name: 'v2_session', value: KUKA, url: new URL(ADRES).origin }]);
const s = await k.newPage();
const ow = [];
s.on('pageerror', (e) => ow.push(String(e)));
const ok = (u, t) => console.log((u ? 'OK   ' : 'FAIL ') + t);
await s.goto(ADRES);
await s.waitForSelector('.dv-tabl tr[data-id]');
await s.waitForTimeout(1000);
await s.setInputFiles('#f-chat', '/tmp/foto.zip');
await s.waitForFunction(() => document.querySelectorAll('#chat-prilozheno img').length === 3, null, { timeout: 30000 });
await s.waitForTimeout(500);
const alts = await s.$$eval('#chat-prilozheno img', (x) => x.map((i) => i.alt));
console.log(alts.join(' | '));
ok(alts.some((a) => a.includes('(спереди)')) && alts.some((a) => a.includes('(сбоку)')), 'русские имена стали видами');
const osh = await s.locator('#chat-oshibka').innerText();
ok(osh.includes('заметка.txt') && osh.includes('битое.jpg') && !osh.includes('_x'), 'лишнее пропущено и названо: ' + osh);
const z = await s.evaluate(() => fetch('api/models/parashyut').then((r) => r.json()));
ok(z.source.photos.length === 3, 'в хранилище 3 фото');
const nom = z.source.photos[0].n;
const r = await s.evaluate((n) => fetch(`api/photos/parashyut/${n}`).then((r) => r.blob()).then((b) => b.size + ' ' + b.type), nom);
ok(/image\/jpeg/.test(r), 'снимки сжаты: ' + r);
await s.setInputFiles('#f-chat', '/tmp/nezip.zip');
await s.waitForFunction(() => document.querySelector('#chat-oshibka').innerText.includes('не похож'), null, { timeout: 8000 });
ok(true, 'не архив — понятная ошибка');
await s.setInputFiles('#f-chat', '/tmp/bomba.zip');
await s.waitForFunction(() => document.querySelector('#chat-oshibka').innerText.includes('bomba'), null, { timeout: 30000 });
ok(true, 'архив-бомба не распаковывается');
ok(ow.length === 0, 'ошибок нет ' + ow.join('|'));
await b.close();
