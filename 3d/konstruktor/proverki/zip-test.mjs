// Архив ZIP в окне чата: фото распаковываются и сохраняются, лишнее пропускается.
import { chromium } from 'playwright-core';
import { readdirSync } from 'node:fs';
const kesh = process.env.HOME + '/.cache/ms-playwright/chromium-1234/';
const chrome = kesh + readdirSync(kesh).find((d) => d.startsWith('chrome-')) + '/chrome';
const { ADRES, KUKA } = process.env;
const b = await chromium.launch({ executablePath: chrome, args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const k = await b.newContext({ viewport: { width: 1440, height: 900 } });
await k.addCookies([{ name: 'v2_session', value: KUKA, url: new URL(ADRES).origin }]);
const s = await k.newPage();
const ow = [];
s.on('pageerror', (e) => ow.push(String(e)));
const ok = (u, t) => console.log((u ? 'OK   ' : 'FAIL ') + t);
await s.goto(ADRES);
await s.waitForSelector('.dv-tabl tr[data-id]');
await s.waitForTimeout(1000);
const zhdat = async () => { await s.waitForFunction(() => document.querySelector('#chat-hod').hidden && !document.querySelector('#b-chat').disabled, null, { timeout: 200000 }); };
const prilozhit = async (f) => { await s.setInputFiles('#f-chat', f); await s.waitForTimeout(300); await zhdat(); };
const skolko = async () => (await s.$$eval('#chat-prilozheno .chip', (x) => x.map((c) => c.title.split(', ').length))).reduce((a, b) => a + b, 0);
await prilozhit('/tmp/t/deflate64.zip');
console.log('oshibka:', await s.locator('#chat-oshibka').innerText());
ok(await skolko() === 3 + 12 + 12, 'Deflate64: снимки, HEIC и кадры из двух видео: ' + await skolko());
console.log(await s.locator('#chat-prilozheno').innerText());
ok(await s.locator('#chat-prilozheno img').count() === 0, 'картинки в чате не выводятся');
ok((await s.locator('#chat-oshibka').innerText()).includes('заметка.txt'), 'лишнее названо');
await prilozhit('/tmp/t/pusto.zip');
ok((await s.locator('#chat-oshibka').innerText()).includes('Пропущено') || (await s.locator('#chat-oshibka').innerText()).includes('не нашлось'), 'архив без снимков — понятно');
await prilozhit('/tmp/t/parol.zip');
ok((await s.locator('#chat-oshibka').innerText()).includes('пароль'), 'архив с паролем — понятно');
await prilozhit('/tmp/t/klip.mov');
ok((await s.locator('#chat-oshibka').innerText()).length >= 0 && await skolko() === 39, 'отдельное видео HEVC: 12 кадров, всего ' + await skolko());
await prilozhit('/tmp/t/bolshoy.zip');
ok(await skolko() > 39, 'архив больше одного куска дошёл целиком: ' + await skolko() + ' | ' + await s.locator('#chat-oshibka').innerText());
ok(ow.length === 0, 'ошибок нет ' + ow.join('|'));
await b.close();
