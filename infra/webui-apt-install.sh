#!/bin/bash
# Установка пакетов из репозиториев Ubuntu — беспарольный шаг агента.
#
# Запуск:
#     sudo webui-apt-install certbot [ещё пакеты ...]
#
# Устанавливается в /usr/local/sbin/webui-apt-install владельцем root и БЕЗ права
# записи пользователю — иначе разрешение на эту обёртку означало бы разрешение
# запускать от root любой код: достаточно переписать сам файл. Отсюда следствие:
# правка этого файла в репозитории сама по себе ничего не меняет, новую версию
# устанавливаете вы:
#     sudo install -o root -g root -m 0755 infra/webui-apt-install.sh /usr/local/sbin/webui-apt-install
#
# ЗАЧЕМ ОБЁРТКА, А НЕ «apt-get install» В СПИСКЕ НАПРЯМУЮ. У apt-get есть два
# способа превратить установку пакета в исполнение произвольного кода от root:
#   - параметр -o APT::Update::Pre-Invoke (и родственные) выполняет команду;
#   - доводом можно дать путь к локальному .deb, чьи сценарии установки идут
#     от root.
# Запись «/usr/bin/apt-get install *» в списке разрешает и то и другое, то есть
# равносильна беспарольному root. Обёртка пропускает только имена пакетов.

set -euo pipefail

if [ "$(id -u)" -ne 0 ]; then
    echo "нужен root: sudo webui-apt-install <пакет> [пакет ...]" >&2
    exit 1
fi
if [ $# -eq 0 ]; then
    echo "Использование: sudo webui-apt-install <пакет> [пакет ...]" >&2
    exit 1
fi

for p in "$@"; do
    # Имя пакета Debian: строчные буквы, цифры и «+ - . _», первым знаком —
    # буква или цифра. Такой вид отсекает доводы-флаги (начинаются с «-») и
    # любые пути (содержат «/»).
    if [[ ! "$p" =~ ^[a-z0-9][a-z0-9+._-]*$ ]]; then
        echo "ОТКАЗ: «$p» не похоже на имя пакета." >&2
        echo "Разрешены только имена пакетов — без флагов, путей и файлов." >&2
        exit 1
    fi
    # Отдельно про .deb: apt-get считает файлом довод с «/» ИЛИ оканчивающийся
    # на .deb, так что «evil.deb» в текущем каталоге прошёл бы проверку выше.
    if [[ "$p" == *.deb ]]; then
        echo "ОТКАЗ: «$p» — файл пакета, а не имя." >&2
        echo "Сценарии установки локального .deb исполняются от root." >&2
        exit 1
    fi
done

echo "=== Обновление списка пакетов ==="
apt-get update

echo "=== Установка: $* ==="
DEBIAN_FRONTEND=noninteractive apt-get install -y "$@"

echo "=== Готово ==="
for p in "$@"; do
    dpkg-query -W -f='  ${Package} ${Version}\n' "$p" 2>/dev/null || echo "  $p: не установился"
done
