def _fill_toc() -> None:
    """Пока поле не обновлено, оглавление — просто список разделов."""
    titles = [x.text for x in doc.paragraphs
              if x.style.name == "Heading 1" and x.text != "Оглавление"]
    run = _toc.getparent()
    _toc.text = titles[0]
    anchor = _toc
    for title in titles[1:]:
        br = OxmlElement("w:br")
        t = OxmlElement("w:t")
        t.text = title
        anchor.addnext(br)
        br.addnext(t)
        anchor = t


