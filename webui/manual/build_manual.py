# ── Оформление ──────────────────────────────────────────────────────────

def _shade(element, fill: str) -> None:
    pr = element.get_or_add_tcPr() if hasattr(element, "get_or_add_tcPr") else element.get_or_add_pPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), fill)
    pr.append(shd)


def _set_font(style, name: str, size: float, bold: bool | None = None, color: RGBColor | None = None) -> None:
    style.font.name = name
    style.font.size = Pt(size)
    rpr = style.element.get_or_add_rPr()
    fonts = rpr.find(qn("w:rFonts"))
    if fonts is None:
        fonts = OxmlElement("w:rFonts")
        rpr.append(fonts)
    for attr in ("w:ascii", "w:hAnsi", "w:cs", "w:eastAsia"):
        fonts.set(qn(attr), name)
    if bold is not None:
        style.font.bold = bold
    if color is not None:
        style.font.color.rgb = color


def setup() -> None:
    section = doc.sections[0]
    section.page_height, section.page_width = Cm(29.7), Cm(21.0)
    section.left_margin = section.right_margin = Cm(2.0)
    section.top_margin, section.bottom_margin = Cm(1.8), Cm(1.8)

    normal = doc.styles["Normal"]
    _set_font(normal, FONT, 10.5, color=INK)
    normal.paragraph_format.space_after = Pt(5)
    normal.paragraph_format.line_spacing = 1.12

    for level, size in ((1, 17), (2, 13.5), (3, 11.5)):
        st = doc.styles[f"Heading {level}"]
        _set_font(st, FONT, size, bold=True, color=INK if level > 1 else RGBColor(0, 0, 0))
        st.paragraph_format.space_before = Pt(16 if level == 1 else 11)
        st.paragraph_format.space_after = Pt(6)
        st.paragraph_format.keep_with_next = True
    for name in ("List Bullet", "List Number"):
        _set_font(doc.styles[name], FONT, 10.5, color=INK)
        doc.styles[name].paragraph_format.space_after = Pt(2)
    _set_font(doc.styles["Caption"], FONT, 9, bold=False, color=RGBColor(0x5F, 0x5B, 0x53))

    # Нижний колонтитул: название и номер страницы
    footer = section.footer.paragraphs[0]
    footer.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    run = footer.add_run("Руководство пользователя · стр. ")
    run.font.size = Pt(8.5)
    run.font.color.rgb = RGBColor(0x8B, 0x86, 0x7C)
    _field(footer, "PAGE", size=8.5)


def _field(paragraph, instr: str, size: float | None = None):
    run = paragraph.add_run()
    if size:
        run.font.size = Pt(size)
    begin = OxmlElement("w:fldChar")
    begin.set(qn("w:fldCharType"), "begin")
    code = OxmlElement("w:instrText")
    code.set(qn("xml:space"), "preserve")
    code.text = instr
    sep = OxmlElement("w:fldChar")
    sep.set(qn("w:fldCharType"), "separate")
    txt = OxmlElement("w:t")
    txt.text = "1" if instr == "PAGE" else "Оглавление появится после обновления поля (F9)."
    end = OxmlElement("w:fldChar")
    end.set(qn("w:fldCharType"), "end")
    for el in (begin, code, sep, txt, end):
        run._r.append(el)
    return txt


# ── Строительные блоки ──────────────────────────────────────────────────

_INLINE = re.compile(r"(\*\*.+?\*\*|`.+?`)")


def _runs(paragraph, text: str) -> None:
    """Разметка внутри абзаца: **жирный** и `код`."""
    for part in _INLINE.split(text):
        if not part:
            continue
        if part.startswith("**"):
            paragraph.add_run(part[2:-2]).bold = True
        elif part.startswith("`"):
            r = paragraph.add_run(part[1:-1])
            r.font.name = MONO
            r._element.rPr.rFonts.set(qn("w:eastAsia"), MONO)
            r.font.size = Pt(9)
        else:
            paragraph.add_run(part)


def h(text: str, level: int = 1) -> None:
    doc.add_heading(text, level)


def p(text: str) -> None:
    _runs(doc.add_paragraph(), text)


def ul(*items: str) -> None:
    for item in items:
        _runs(doc.add_paragraph(style="List Bullet"), item)


def ol(*items: str) -> None:
    """Нумерованный список. Номер пишется текстом: у Word общая нумерация
    стиля продолжалась бы через весь документ."""
    for i, item in enumerate(items, 1):
        para = doc.add_paragraph()
        para.paragraph_format.left_indent = Cm(0.9)
        para.paragraph_format.first_line_indent = Cm(-0.6)
        para.paragraph_format.space_after = Pt(2)
        para.add_run(f"{i}. ")
        _runs(para, item)


def code(text: str) -> None:
    table = doc.add_table(rows=1, cols=1)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    cell = table.cell(0, 0)
    _shade(cell._tc, "F1EFEA")
    para = cell.paragraphs[0]
    para.paragraph_format.space_after = Pt(0)
    for i, line in enumerate(text.strip("\n").split("\n")):
        if i:
            para.add_run().add_break()
        r = para.add_run(line)
        r.font.name = MONO
        r._element.rPr.rFonts.set(qn("w:eastAsia"), MONO)
        r.font.size = Pt(8.5)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)


def note(text: str, kind: str = "info") -> None:
    fill, label = {"info": ("EAF1F8", "Совет"), "warn": ("FDF4D0", "Важно"),
                   "danger": ("FBE3E1", "Осторожно")}[kind]
    table = doc.add_table(rows=1, cols=1)
    cell = table.cell(0, 0)
    _shade(cell._tc, fill)
    para = cell.paragraphs[0]
    para.paragraph_format.space_after = Pt(0)
    para.add_run(label + ". ").bold = True
    _runs(para, text)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)


def table(header: list[str], rows: list[list[str]], widths: list[float] | None = None) -> None:
    t = doc.add_table(rows=1, cols=len(header))
    t.style = "Table Grid"
    for i, title in enumerate(header):
        cell = t.rows[0].cells[i]
        _shade(cell._tc, "ECEAE4")
        cell.paragraphs[0].paragraph_format.space_after = Pt(0)
        r = cell.paragraphs[0].add_run(title)
        r.bold = True
        r.font.size = Pt(9.5)
    for row in rows:
        cells = t.add_row().cells
        for i, value in enumerate(row):
            para = cells[i].paragraphs[0]
            para.paragraph_format.space_after = Pt(0)
            _runs(para, value)
            for r in para.runs:
                r.font.size = Pt(9.5)
    if widths:
        t.autofit = False
        for i, w in enumerate(widths):
            t.columns[i].width = Cm(w)
        for row in t.rows:
            for i, w in enumerate(widths):
                row.cells[i].width = Cm(w)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)


def img(name: str, caption: str, width: float = 17.0) -> None:
    global _figure
    path = SHOTS / f"{name}.png"
    if not path.exists():
        raise SystemExit(f"нет снимка {path} — сначала manual/make_shots.py")
    _figure += 1
    para = doc.add_paragraph()
    para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    para.paragraph_format.keep_with_next = True
    para.paragraph_format.space_after = Pt(2)
    para.add_run().add_picture(str(path), width=Cm(width))
    cap = doc.add_paragraph(f"Рисунок {_figure}. {caption}", style="Caption")
    cap.alignment = WD_ALIGN_PARAGRAPH.CENTER


def page_break() -> None:
    doc.add_paragraph().add_run().add_break(WD_BREAK.PAGE)


