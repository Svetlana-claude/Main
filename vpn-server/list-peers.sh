#!/usr/bin/env bash
# Сводка по клиентам для панели управления: имя, адрес, ключ, трафик, рукопожатие.
#
#   sudo ./list-peers.sh
#
# Вывод — по строке на клиента, поля разделены табуляцией:
#
#   имя  адрес  открытый_ключ  принято_байт  передано_байт  рукопожатие  адрес_клиента
#
# Числами, а не в «1.05 MiB» и «2 minutes ago»: разбирать человеческий вид
# на стороне панели — значит зависеть от языка и округления. Рукопожатие —
# время в секундах от начала эпохи, 0 у тех, кто ни разу не подключался.
#
# Имена живут только в конфиге сервера (строки «# client: имя»), а трафик —
# только в выводе `wg show`, поэтому одно сшивается с другим по открытому ключу.
set -euo pipefail

WG_DIR="${WG_DIR:-/etc/wireguard}"   # переопределяется только ради проверок

die() { printf 'Ошибка: %s\n' "$*" >&2; exit 1; }

[ "$(id -u)" -eq 0 ] || die "нужны права root"
[ -f "$WG_DIR/params" ] || die "сервер не настроен, сначала install-wireguard.sh"
# shellcheck disable=SC1091
. "$WG_DIR/params"

CONF="$WG_DIR/$WG_IFACE.conf"
[ -f "$CONF" ] || die "нет конфига $CONF"

awk -F'\t' '
    # Первый файл — конфиг сервера: собираем «открытый ключ -> имя».
    FNR == NR {
        if ($0 ~ /^# client: /) { name = substr($0, 11) }   # «# client: » — 10 знаков
        else if ($0 ~ /^PublicKey/) {
            split($0, a, " = ")
            if (name != "") { names[a[2]] = name; name = "" }
        }
        next
    }
    # Второй — дамп wg. Первая строка описывает сам интерфейс, она не нужна.
    FNR == 1 { next }
    {
        # Поля дампа: 1 ключ, 2 общий секрет, 3 адрес клиента, 4 разрешённые
        # адреса, 5 рукопожатие, 6 принято, 7 передано, 8 keepalive.
        n = ($1 in names) ? names[$1] : "?"
        endpoint = ($3 == "(none)") ? "" : $3
        print n "\t" $4 "\t" $1 "\t" $6 "\t" $7 "\t" $5 "\t" endpoint
    }
' "$CONF" <(wg show "$WG_IFACE" dump)
