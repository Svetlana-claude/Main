# shellcheck shell=bash
# shellcheck disable=SC2034  # файл подключается через `.`, значения читают другие скрипты
# Параметры развёртывания. Единственный файл, который правят под сервер.
#
# BASE и STATE задаются через ${...:-}, чтобы набор можно было прогнать из
# временного каталога (BASE=/tmp/sec STATE=/tmp/sec ./audit.sh), не трогая
# боевую установку. Жёсткое присваивание означало бы, что карантин и отчёты
# пробного прогона уедут в боевой каталог.

# КОД. Принадлежит root, пользователю на запись недоступен. Здесь же эталон и
# карантин: первый не должен меняться бесшумно, во втором лежит изъятое.
BASE=${BASE:-/opt/secaudit}

# СОСТОЯНИЕ. Принадлежит пользователю, из-под которого идёт cron: снимки,
# отчёты, журнал. Разнесено с кодом намеренно — см. README, раздел «Раскладка».
STATE=${STATE:-/var/lib/secaudit}

ADMIN_USER=mokeeva

SSH_PORT=22
# Режим входа по SSH: key — только ключи, password — разрешён пароль.
# От него зависит набор инвариантов в diff.sh и правила SSH в apply-firewall.sh.
#
# Решение от 14.09.2026: вход только по ключам. Ключ mokeeva-workstation
# проверен настоящим подключением — сперва с сервера (12.09), затем вами со
# своего компьютера (14.09). В режиме key `harden-ssh` выключает пароль, а
# diff.sh проверяет инвариант «пароли для SSH отключены» каждую ночь.
#
# ⚠️ Файл вступает в силу вместе с обёрткой: до `infra/switch-to-keys.sh`
# на машине действует прежняя копия с password.
SSH_AUTH_MODE=key
# Парольный режим: откуда допускается вход (пусто — отовсюду, но с лимитом темпа)
ADMIN_NETS=""
# Парольный режим: порог «всплеск подбора» — неудачных попыток за сутки
BRUTE_THRESHOLD=2000

# Лимит темпа подключений к SSH с одного адреса: сколько новых соединений
# в минуту пропускать, прежде чем отбрасывать.
#
# В инструкции стоит 4. Здесь 10, и это осознанно: SFTP-клиент открывает
# несколько соединений подряд, и на четырёх можно отрезать себя во время
# обычной работы. Десять всё равно превращают тысячи попыток подбора в
# десятки, а основную работу по баням делает fail2ban с джейлом recidive.
SSH_RATE_HITCOUNT=10

# Публичные TCP-порты и диапазоны через запятую (формат multiport).
# Взято по факту: ss -tulnH | awk '$5 ~ /^(0\.0\.0\.0|\*|\[::\])/'
PUB_TCP="80,443"

# Публичные UDP-порты. Параметра НЕТ в исходной инструкции, и это её изъян:
# apply-firewall.sh открывал только TCP, а WireGuard слушает 51820/udp —
# первое же применение правил отрезало бы VPN молча. Ровно та ловушка, про
# которую предупреждает §10 инструкции.
PUB_UDP="51820"

# Интерфейсы, трафик с которых принимается без разбора портов. Клиент VPN с
# полным туннелем ходит к серверу по 10.8.0.1, и это INPUT с wg0: без такого
# правила панель по туннелю перестанет открываться.
TRUSTED_IFACES="wg0"

# Адреса в постоянный блок (управляющие серверы известных закладок), через пробел
BLOCKED_V4=""
# Белый список fail2ban: обязательно свой адрес
TRUSTED_IPS="127.0.0.1/8 ::1 10.8.0.0/24"
# Службы, состояние которых сверяется после перезагрузки. Docker на машине нет.
SERVICES="ssh nginx postgresql fail2ban webui wg-quick@wg0"

# Команда разбора. Пусто — раздел «Оценка/Внимание/Рекомендации» не формируется.
ANALYZER=""
ANALYZER_TIMEOUT=600

RETENTION_DAYS=90
